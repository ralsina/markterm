#!/bin/sh
# Generates build/math_res.S, build/math_res_index.cpp and
# build/math_res_index.h from the MicroTeX resource tree
# (microtex/res): every file becomes an .incbin blob, and the index
# maps its res-relative path to {data, size}. The resources are
# embedded in the static library and extracted to a temp directory
# at runtime when no installed resource directory is found, so
# markpdf needs no external files to render math.
#
# The generated .S uses paths relative to this script's directory,
# so it must be regenerated (it is, via the manifest dependency)
# whenever the tree moves.
set -e

root=$(cd "$(dirname "$0")" && pwd)
res="$root/microtex/res"
build="$root/build"
mkdir -p "$build"

manifest="$build/math_res.manifest"
(cd "$res" && find . -type f | sed 's|^\./||' | LC_ALL=C sort) > "$manifest"

asm="$build/math_res.S"
index_cpp="$build/math_res_index.cpp"
index_h="$build/math_res_index.h"

{
    echo "/* Generated by gen-math-res.sh — do not edit. */"
    echo "/* Embeds every file under microtex/res via .incbin. */"
    echo "#if defined(__ELF__)"
    echo ".section .rodata"
    echo "#endif"
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        echo ".global math_res_$sym"
        echo "math_res_$sym:"
        echo "    .incbin \"$res/$file\""
        echo "math_res_${sym}_end:"
        echo ".global math_res_${sym}_end"
    done < "$manifest"
} > "$asm"

{
    echo "// Generated by gen-math-res.sh — do not edit."
    echo "#include \"math_res_index.h\""
    echo
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        echo "extern \"C\" const unsigned char math_res_${sym}[];"
        echo "extern \"C\" const unsigned char math_res_${sym}_end[];"
    done < "$manifest"
    echo
    echo "extern \"C\" const MathResFile math_res_files[] = {"
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        echo "    {\"$file\", math_res_$sym, (unsigned int)(math_res_${sym}_end - math_res_$sym)},"
    done < "$manifest"
    echo "};"
    echo "extern \"C\" const unsigned int math_res_files_count = \\
    (unsigned int)(sizeof(math_res_files) / sizeof(math_res_files[0]));"
} > "$index_cpp"

{
    echo "// Generated by gen-math-res.sh — do not edit."
    echo "#ifndef MATH_RES_INDEX_H"
    echo "#define MATH_RES_INDEX_H"
    echo
    echo "struct MathResFile {"
    echo "    const char* path;"
    echo "    const unsigned char* data;"
    echo "    unsigned int size;"
    echo "};"
    echo
    echo "extern \"C\" const MathResFile math_res_files[];"
    echo "extern \"C\" const unsigned int math_res_files_count;"
    echo
    echo "#endif  // MATH_RES_INDEX_H"
} > "$index_h"

echo "math-res: embedded $(wc -l < "$manifest") files ($(du -sh "$res" | cut -f1)) from $res"

#!/bin/sh
# Generates build/math_res_data.cpp, build/math_res_index.cpp and
# build/math_res_index.h from the MicroTeX resource tree
# (microtex/res): every file becomes a string-literal byte array (all
# bytes as three-digit octal escapes, so no byte needs special
# casing), and the index maps its res-relative path to {data, size}.
# The resources are embedded in the static library and extracted to a
# temp directory at runtime when no installed resource directory is
# found, so markpdf needs no external files to render math.
#
# A generated C++ file (not .incbin assembly) keeps the embedding
# identical on every object format: assembler+ranlib+linker
# combinations on Mach-O and COFF proved unreliable for symbols
# defined in a bare .S blob file.
set -e

root=$(cd "$(dirname "$0")" && pwd)
res="$root/microtex/res"
build="$root/build"
mkdir -p "$build"

manifest="$build/math_res.manifest"
(cd "$res" && find . -type f | sed 's|^\./||' | LC_ALL=C sort) > "$manifest"

data_cpp="$build/math_res_data.cpp"
index_cpp="$build/math_res_index.cpp"
index_h="$build/math_res_index.h"

# Every byte as an octal escape, quoted 96 escapes per line.
{
    echo "// Generated by gen-math-res.sh — do not edit."
    echo "// Embeds every file under microtex/res as string literals."
    echo
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        size=$(wc -c < "$res/$file" | tr -d ' ')
        octal=$(od -An -v -tu1 "$res/$file" | tr -s ' \n' '\n' | sed '/^$/d' | awk '{printf "\\%03o", $1; if (NR % 96 == 0) printf "\n"}')
        echo "extern \"C\" const unsigned char math_res_${sym}[]" =
        if [ "$size" -eq 0 ]
        then
            echo '""'
        else
            printf '%s\n' "$octal" | sed '/^$/d; s/.*/"&"/'
        fi
        echo ";  /* $size bytes: $file */"
        echo
    done < "$manifest"
} > "$data_cpp"

{
    echo "// Generated by gen-math-res.sh — do not edit."
    echo "#include \"math_res_index.h\""
    echo
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        echo "extern \"C\" const unsigned char math_res_${sym}[];"
    done < "$manifest"
    echo
    echo "extern \"C\" const MathResFile math_res_files[] = {"
    while IFS= read -r file; do
        [ -n "$file" ] || continue
        sym=$(printf '%s' "$file" | sed 's/[^a-zA-Z0-9]/_/g')
        size=$(wc -c < "$res/$file" | tr -d ' ')
        echo "    {\"$file\", math_res_$sym, $size},"
    done < "$manifest"
    echo "};"
    echo "extern \"C\" const unsigned int math_res_files_count = \\
    (unsigned int)(sizeof(math_res_files) / sizeof(math_res_files[0]));"
} > "$index_cpp"

{
    echo "// Generated by gen-math-res.sh — do not edit."
    echo "#ifndef MATH_RES_INDEX_H"
    echo "#define MATH_RES_INDEX_H"
    echo
    echo "struct MathResFile {"
    echo "    const char* path;"
    echo "    const unsigned char* data;"
    echo "    unsigned int size;"
    echo "};"
    echo
    echo "extern \"C\" const MathResFile math_res_files[];"
    echo "extern \"C\" const unsigned int math_res_files_count;"
    echo
    echo "#endif  // MATH_RES_INDEX_H"
} > "$index_h"

echo "math-res: embedded $(wc -l < "$manifest") files ($(du -sh "$res" | cut -f1)) from $res"
